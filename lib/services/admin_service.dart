  /// Validate audio file
  bool validateAudioFile(File file) {
    try {
      final fileName = file.path.split('/').last.toLowerCase();
      final extension = fileName.split('.').last;

      // Check extension
      if (!['mp3', 'wav', 'm4a'].contains(extension)) {
        return false;
      }

      // Check file size (max 50MB)
      final fileSizeInBytes = file.lengthSync();
      final fileSizeInMB = fileSizeInBytes / (1024 * 1024);
      if (fileSizeInMB > 50) {
        return false;
      }

      return true;
    } catch (e) {
      print('Error validating audio file: $e');
      return false;
    }
  }

  /// Validate image file
  bool validateImageFile(File file) {
    try {
      final fileName = file.path.split('/').last.toLowerCase();
      final extension = fileName.split('.').last;

      // Check extension
      if (!['jpg', 'jpeg', 'png'].contains(extension)) {
        return false;
      }

      // Check file size (max 5MB)
      final fileSizeInBytes = file.lengthSync();
      final fileSizeInMB = fileSizeInBytes / (1024 * 1024);
      if (fileSizeInMB > 5) {
        return false;
      }

      return true;
    } catch (e) {
      print('Error validating image file: $e');
      return false;
    }
  }
