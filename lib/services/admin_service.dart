  /// Submit a new upload for admin review
  Future<AdminUpload?> submitUpload({
    required String uploaderId,
    required String artistName,
    required String songTitle,
    String? albumTitle,
    String? genre,
    String? language,
    required File audioFile,
    File? coverImage,
  }) async {
    try {
      // Generate unique paths for uploads
      final timestamp = DateTime.now().millisecondsSinceEpoch;
      final audioFileName = audioFile.path.split('/').last;
      final audioPath = 'uploads/$uploaderId/$timestamp-$audioFileName';

      // Upload audio file
      print('Uploading audio file...');
      await _supabaseService.uploadFile(audioFile, audioPath);

      // Upload cover image if provided
      String? coverPath;
      if (coverImage != null) {
        final coverFileName = coverImage.path.split('/').last;
        coverPath = 'uploads/$uploaderId/covers/$timestamp-$coverFileName';
        print('Uploading cover image...');
        await _supabaseService.uploadFile(coverImage, coverPath);
      }

      // Create upload record
      final upload = AdminUpload(
        id: '', // Will be generated by Supabase
        uploaderId: uploaderId,
        artistName: artistName,
        songTitle: songTitle,
        albumTitle: albumTitle,
        genre: genre,
        language: language ?? 'en',
        storagePath: audioPath,
        coverImage: coverPath,
        status: UploadStatus.pending,
        createdAt: DateTime.now(),
        updatedAt: DateTime.now(),
      );

      final savedUpload = await _supabaseService.createUpload(upload);
      print('Upload submitted successfully!');
      return savedUpload;
    } catch (e) {
      print('Error submitting upload: $e');
      return null;
    }
  }

