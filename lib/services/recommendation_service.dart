  /// Get songs by mood
  Future<List<Song>> getSongsByMood(String mood, {int limit = 20}) async {
    try {
      // Map moods to genres
      String? genre;
      switch (mood.toLowerCase()) {
        case 'worship':
          genre = 'Worship';
          break;
        case 'praise':
          genre = 'Praise';
          break;
        case 'reflection':
          genre = 'Gospel';
          break;
        case 'celebration':
          genre = 'Afro-Gospel';
          break;
        default:
          genre = null;
      }

      return await _supabaseService.fetchSongs(
        genre: genre,
        limit: limit,
      );
    } catch (e) {
      print('Error getting songs by mood: $e');
      return [];
    }
  }

