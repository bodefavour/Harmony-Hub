import 'package:flutter/material.dart';
import '../../models/song.dart';
import '../../models/album.dart';
import '../../models/playlist.dart';
import '../../services/supabase_service.dart';
import '../../services/audio_service.dart';

class LibraryController extends ChangeNotifier {
  final SupabaseService _supabaseService;
  final AudioService _audioService;

  List<Song> _recentSongs = [];
  List<Song> _favoriteSongs = [];
  List<Album> _favoriteAlbums = [];
  List<Playlist> _playlists = [];
  
  bool _isLoading = false;
  String? _error;

  LibraryController({
    required SupabaseService supabaseService,
    required AudioService audioService,
  })  : _supabaseService = supabaseService,
        _audioService = audioService;

  // Getters
  List<Song> get recentSongs => _recentSongs;
  List<Song> get favoriteSongs => _favoriteSongs;
  List<Album> get favoriteAlbums => _favoriteAlbums;
  List<Playlist> get playlists => _playlists;
  bool get isLoading => _isLoading;
  String? get error => _error;

  bool get hasRecentSongs => _recentSongs.isNotEmpty;
  bool get hasFavoriteSongs => _favoriteSongs.isNotEmpty;
  bool get hasFavoriteAlbums => _favoriteAlbums.isNotEmpty;
  bool get hasPlaylists => _playlists.isNotEmpty;

  /// Initialize and load all library data
  Future<void> initialize(String userId) async {
    _isLoading = true;
    _error = null;
    notifyListeners();

    try {
      // Load all data in parallel
      await Future.wait([
        _loadRecentSongs(userId),
        _loadFavoriteSongs(userId),
        _loadFavoriteAlbums(userId),
        _loadPlaylists(userId),
      ]);

      _isLoading = false;
      notifyListeners();
    } catch (e) {
      _error = 'Failed to load library: ${e.toString()}';
      _isLoading = false;
      notifyListeners();
    }
  }

  /// Load recently played songs
  Future<void> _loadRecentSongs(String userId) async {
    try {
      _recentSongs = await _supabaseService.getRecentSongs(userId, limit: 10);
      notifyListeners();
    } catch (e) {
      print('Error loading recent songs: $e');
    }
  }

  /// Load favorite songs
  Future<void> _loadFavoriteSongs(String userId) async {
    try {
      _favoriteSongs = await _supabaseService.getUserFavorites(userId);
      notifyListeners();
    } catch (e) {
      print('Error loading favorite songs: $e');
    }
  }

  /// Load favorite albums
  Future<void> _loadFavoriteAlbums(String userId) async {
    try {
      _favoriteAlbums = await _supabaseService.getFavoriteAlbums(userId);
      notifyListeners();
    } catch (e) {
      print('Error loading favorite albums: $e');
    }
  }

  /// Load user's playlists
  Future<void> _loadPlaylists(String userId) async {
    try {
      _playlists = await _supabaseService.getUserPlaylists(userId);
      notifyListeners();
    } catch (e) {
      print('Error loading playlists: $e');
    }
  }

  /// Play a song from the library
  Future<void> playSong(Song song) async {
    try {
      await _audioService.playSong(song);
    } catch (e) {
      _error = 'Failed to play song: ${e.toString()}';
      notifyListeners();
    }
  }

  /// Create a new playlist
  Future<bool> createPlaylist(String userId, String name, {String? description}) async {
    try {
      _isLoading = true;
      notifyListeners();

      final playlist = Playlist(
        id: '', // Will be generated by Supabase
        userId: userId,
        title: name,
        description: description,
        createdAt: DateTime.now(),
        updatedAt: DateTime.now(),
      );

      final created = await _supabaseService.createPlaylist(playlist);
      
      if (created != null) {
        _playlists.insert(0, created);
      }

      _isLoading = false;
      notifyListeners();
      return created != null;
    } catch (e) {
      _error = 'Failed to create playlist: ${e.toString()}';
      _isLoading = false;
      notifyListeners();
      return false;
    }
  }

  /// Refresh library data
  Future<void> refresh(String userId) async {
    await initialize(userId);
  }

  /// Clear error
  void clearError() {
    _error = null;
    notifyListeners();
  }
}
